import { describe, expect, it } from 'vitest';
import {
  parseYarnLock,
  resolvePackageKey,
  resolveTransitive,
  type NpmLockfile,
} from '../src/parser/lockfile.js';
import { classifySpec } from '../src/parser/manifest.js';

/**
 * Árbol simulado npm:
 *   app
 *   ├─ express@4 ─┬─ debug@2 ── ms@2.0 (anidado en debug)
 *   │             ├─ cookie
 *   │             └─ qs ── side-channel
 *   ├─ debug@4 (hoisted) ── ms@2.1 (hoisted)
 *   └─ lodash4 (alias de lodash)
 */
const npmLock: NpmLockfile = {
  type: 'npm',
  lockfileVersion: 3,
  packages: {
    '': { dependencies: { express: '^4', debug: '^4', lodash4: 'npm:lodash@^4' } },
    'node_modules/express': { version: '4.21.0', dependencies: { debug: '2.6.9', cookie: '0.7', qs: '6', 'not-installed': '1' } },
    'node_modules/express/node_modules/debug': { version: '2.6.9', dependencies: { ms: '2.0.0' } },
    'node_modules/express/node_modules/ms': { version: '2.0.0' },
    'node_modules/debug': { version: '4.3.7', dependencies: { ms: '^2.1.3' } },
    'node_modules/ms': { version: '2.1.3' },
    'node_modules/cookie': { version: '0.7.1' },
    'node_modules/qs': { version: '6.13.0', dependencies: { 'side-channel': '^1' } },
    'node_modules/side-channel': { version: '1.0.6', resolved: 'git+ssh://git@github.com/x/side-channel.git' },
    'node_modules/lodash4': { name: 'lodash', version: '4.17.21' },
  },
};

const direct = [
  classifySpec('express', '^4', 'dependencies'),
  classifySpec('debug', '^4', 'dependencies'),
  classifySpec('lodash4', 'npm:lodash@^4', 'dependencies'),
];

describe('resolvePackageKey (npm)', () => {
  const pk = npmLock.packages!;
  it('prefiere la copia anidada más cercana', () => {
    expect(resolvePackageKey(pk, 'debug', 'node_modules/express')).toBe('node_modules/express/node_modules/debug');
    expect(resolvePackageKey(pk, 'ms', 'node_modules/express/node_modules/debug')).toBe('node_modules/express/node_modules/ms');
  });
  it('sube hasta la raíz (hoisting)', () => {
    expect(resolvePackageKey(pk, 'cookie', 'node_modules/express')).toBe('node_modules/cookie');
    expect(resolvePackageKey(pk, 'ms', 'node_modules/debug')).toBe('node_modules/ms');
  });
  it('devuelve null si no está instalado', () => {
    expect(resolvePackageKey(pk, 'not-installed', 'node_modules/express')).toBeNull();
  });
});

describe('resolveTransitive (npm)', () => {
  it('devuelve solo transitivas, deduplicadas, con profundidad y camino más corto', () => {
    const result = resolveTransitive(npmLock, direct, { maxDepth: Number.POSITIVE_INFINITY });
    const byName = Object.fromEntries(result.map((d) => [d.name, d]));

    expect(Object.keys(byName).sort()).toEqual(['cookie', 'ms', 'qs', 'side-channel']);
    expect(byName.cookie).toMatchObject({ kind: 'transitive', depth: 2, via: ['express'], spec: '0.7.1' });
    expect(byName['side-channel']).toMatchObject({ depth: 3, via: ['express', 'qs'] });
    expect(byName.ms).toMatchObject({ depth: 2, via: ['debug'] });
    expect(byName.debug).toBeUndefined();
  });

  it('marca como no evaluables las instaladas desde git', () => {
    const result = resolveTransitive(npmLock, direct, { maxDepth: Number.POSITIVE_INFINITY });
    expect(result.find((d) => d.name === 'side-channel')?.unsupportedReason).toMatch(/git/);
  });

  it('respeta --depth', () => {
    expect(resolveTransitive(npmLock, direct, { maxDepth: 1 })).toEqual([]);
    const d2 = resolveTransitive(npmLock, direct, { maxDepth: 2 }).map((d) => d.name);
    expect(d2).toContain('cookie');
    expect(d2).not.toContain('side-channel');
  });

  it('usa el nombre real del registry en alias del lockfile', () => {
    const l: NpmLockfile = {
      type: 'npm',
      packages: {
        '': {},
        'node_modules/a': { version: '1.0.0', dependencies: { u: 'npm:underscore@1' } },
        'node_modules/u': { name: 'underscore', version: '1.13.0' },
      },
    };
    const r = resolveTransitive(l, [classifySpec('a', '1', 'dependencies')], { maxDepth: 10 });
    expect(r[0]).toMatchObject({ name: 'u', registryName: 'underscore' });
  });

  it('rechaza lockfileVersion 1', () => {
    expect(() => resolveTransitive({ type: 'npm', lockfileVersion: 1 }, direct, { maxDepth: 5 })).toThrow(/npm >= 7/);
  });
});

describe('Yarn v1 lockfile', () => {
  const sampleYarnLock = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.24.7":
  version "7.24.7"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.24.7.tgz#4f14194a05be8848dbb639d828d79927638fe556"
  dependencies:
    "@babel/highlight" "^7.24.7"

"@babel/highlight@^7.24.7":
  version "7.24.7"
  resolved "https://registry.yarnpkg.com/@babel/highlight/-/highlight-7.24.7.tgz#a05ab1df134b286558aae0edfc1e450fd149eacb"
  dependencies:
    chalk "^2.4.2"
    js-tokens "^4.0.0"

chalk@^2.4.2:
  version "2.4.2"
  resolved "https://registry.yarnpkg.com/chalk/-/chalk-2.4.2.tgz#cd42541677a54333cf541a49108c1432b44c9424"
  dependencies:
    ansi-styles "^3.2.1"

ansi-styles@^3.2.1:
  version "3.2.1"
  resolved "https://registry.yarnpkg.com/ansi-styles/-/ansi-styles-3.2.1.tgz#41fbb20243e50b12be0f04b8dedbf07520ce841d"

git-pkg@^1.0.0:
  version "1.0.0"
  resolved "git+https://github.com/foo/git-pkg.git#commit"
`;

  it('parseYarnLock parsea cabeceras múltiples y dependencias correctamente', () => {
    const lock = parseYarnLock(sampleYarnLock);
    expect(lock.type).toBe('yarn');
    expect(lock.entries.has('@babel/code-frame@^7.0.0')).toBe(true);
    expect(lock.entries.has('@babel/code-frame@^7.24.7')).toBe(true);

    const framePkg = lock.entries.get('@babel/code-frame@^7.0.0')!;
    expect(framePkg.name).toBe('@babel/code-frame');
    expect(framePkg.version).toBe('7.24.7');
    expect(framePkg.dependencies).toEqual({ '@babel/highlight': '^7.24.7' });
  });

  it('resolveTransitive con yarn.lock resuelve la cadena de dependencias', () => {
    const lock = parseYarnLock(sampleYarnLock);
    const directDeps = [classifySpec('@babel/code-frame', '^7.0.0', 'dependencies')];

    const result = resolveTransitive(lock, directDeps, { maxDepth: 10 });
    const byName = Object.fromEntries(result.map((d) => [d.name, d]));

    expect(byName['@babel/highlight']).toMatchObject({
      kind: 'transitive',
      depth: 2,
      via: ['@babel/code-frame'],
      spec: '7.24.7',
    });

    expect(byName['chalk']).toMatchObject({
      kind: 'transitive',
      depth: 3,
      via: ['@babel/code-frame', '@babel/highlight'],
      spec: '2.4.2',
    });

    expect(byName['ansi-styles']).toMatchObject({
      kind: 'transitive',
      depth: 4,
      via: ['@babel/code-frame', '@babel/highlight', 'chalk'],
    });
  });

  it('respeta --depth en yarn.lock', () => {
    const lock = parseYarnLock(sampleYarnLock);
    const directDeps = [classifySpec('@babel/code-frame', '^7.0.0', 'dependencies')];

    const d2 = resolveTransitive(lock, directDeps, { maxDepth: 2 }).map((d) => d.name);
    expect(d2).toContain('@babel/highlight');
    expect(d2).not.toContain('chalk');
  });

  it('detecta URLs git en paquetes resueltos de yarn.lock', () => {
    const lock = parseYarnLock(sampleYarnLock);
    const directDeps = [classifySpec('git-pkg', '^1.0.0', 'dependencies')];
    const result = resolveTransitive(lock, directDeps, { maxDepth: 2 });
    // git-pkg es directa; si fuera transitiva se marcaría unsupported
    expect(result).toEqual([]);
  });
});
